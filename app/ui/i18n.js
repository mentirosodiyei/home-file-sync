let LANG = "es";

/** "ca…" → catalán, "es…" → castellano, cualquier otro → inglés. */
function pickLang(tag) {
  const t = String(tag || "").toLowerCase();
  return t.startsWith("ca") ? "ca" : t.startsWith("es") ? "es" : "en";
}

/** Texto traducido; cada `{}` se sustituye por el siguiente argumento. */
function t(key, ...args) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.es[key] ?? key;
  for (const a of args) s = s.replace("{}", a);
  return s;
}

/** Aplica el idioma a los textos fijos del HTML (data-i18n…). */
function setLang(tag) {
  LANG = pickLang(tag);
  document.documentElement.lang = LANG;
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document.querySelectorAll("[data-i18n-html]").forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml)));
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", el.title);
  });
}
